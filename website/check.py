#!/usr/bin/env python3
"""Sanity checks for every page in the static site.

Validates, with no third-party dependencies:

  * HTML tag balance (catches unclosed / mismatched elements)
  * duplicate `id`s within a page
  * every local `href` / `src` resolves to a file that exists
  * every `#fragment` resolves to an `id` in the target page
  * `aria-controls` and `data-copy` point at ids in the same page
  * hand-highlighted code blocks contain nothing but `tk-*` spans

Covers both the hand-written pages and the ones generated by `build-docs.mjs`.

Usage:
    python3 check.py
"""

from __future__ import annotations

import html.parser
import os
import re
import sys
from urllib.parse import unquote

ROOT = os.path.dirname(os.path.abspath(__file__))

VOID = {
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link",
    "meta", "param", "source", "track", "wbr",
}
EXTERNAL = ("http://", "https://", "mailto:", "tel:", "data:", "//")


class Page(html.parser.HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.stack: list[tuple[str, tuple[int, int]]] = []
        self.errors: list[str] = []
        self.ids: set[str] = set()
        self.references: list[str] = []
        self.controls: list[str] = []
        self.copy_targets: list[str] = []

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)

        if "id" in attributes:
            if attributes["id"] in self.ids:
                self.errors.append(f"duplicate id: {attributes['id']}")
            self.ids.add(attributes["id"])

        if "aria-controls" in attributes:
            self.controls.append(attributes["aria-controls"])
        if "data-copy" in attributes:
            self.copy_targets.append(attributes["data-copy"])

        for key in ("href", "src"):
            if key in attributes:
                self.references.append(attributes[key])

        if tag not in VOID:
            self.stack.append((tag, self.getpos()))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID and self.stack:
            self.stack.pop()

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if not self.stack:
            self.errors.append(f"stray </{tag}> at line {self.getpos()[0]}")
            return
        opened, position = self.stack.pop()
        if opened != tag:
            self.errors.append(
                f"mismatched </{tag}> at line {self.getpos()[0]} "
                f"(expected </{opened}>, opened at line {position[0]})"
            )


def html_files() -> list[str]:
    found: list[str] = []
    for directory, subdirectories, filenames in os.walk(ROOT):
        subdirectories[:] = [name for name in subdirectories if name not in {"node_modules", ".git"}]
        for name in sorted(filenames):
            if name.endswith(".html"):
                found.append(os.path.join(directory, name))
    return found


def parse(path: str) -> Page:
    with open(path, encoding="utf-8") as handle:
        source = handle.read()
    page = Page()
    page.feed(source)
    page.source = source  # type: ignore[attr-defined]
    return page


def main() -> int:
    pages = html_files()
    if not pages:
        print("no HTML files found", file=sys.stderr)
        return 1

    parsed: dict[str, Page] = {}
    problems: list[str] = []

    for path in pages:
        page = parse(path)
        parsed[path] = page
        label = os.path.relpath(path, ROOT)

        for error in page.errors:
            problems.append(f"{label}: {error}")

        if page.stack:
            problems.append(f"{label}: unclosed tags {[tag for tag, _ in page.stack]}")

        for target in page.controls + page.copy_targets:
            if target not in page.ids:
                problems.append(f"{label}: dangling reference to id '{target}'")

        for reference in page.references:
            if reference.startswith(EXTERNAL):
                continue

            path_part, _, fragment = reference.partition("#")
            path_part = unquote(path_part)

            if path_part:
                resolved = os.path.normpath(os.path.join(os.path.dirname(path), path_part))
                if not os.path.exists(resolved):
                    problems.append(f"{label}: missing local file '{reference}'")
                    continue
                if resolved.endswith(".html"):
                    if resolved not in parsed:
                        parsed[resolved] = parse(resolved)
                    if fragment and fragment not in parsed[resolved].ids:
                        problems.append(f"{label}: missing anchor '{reference}'")
            elif fragment and fragment not in page.ids:
                problems.append(f"{label}: missing anchor '#{fragment}'")

    # Guard the hand-highlighted samples: a stray tag means a broken snippet.
    for path in pages:
        label = os.path.relpath(path, ROOT)
        source = parsed[path].source  # type: ignore[attr-defined]
        for identifier, block in re.findall(
            r'<code id="(code-[^"]*)">(.*?)</code>', source, re.S
        ):
            for tag in re.findall(r"</?([a-zA-Z][\w-]*)", block):
                if tag != "span":
                    problems.append(f"{label}: unexpected <{tag}> in #{identifier}")

    print(f"checked {len(pages)} pages")

    if problems:
        print("\nproblems:")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print("structure, references and anchors all valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
